namespace {
// Probability is a 0-100 percentage: 100 means "always inject".
constexpr int32_t PROBABILITY_MAX_PERCENT = 100;
// Length of the "file:" URI prefix used by in-memory database paths.
constexpr size_t FILE_URI_PREFIX_LEN = 5;
} // namespace

// Schema of rdb_fault_inject_config.json, parsed only through
// Serializable::Unmarshal; the injector logic never touches json objects.

// count/probability budget of one entry. Absent or null fields keep the
// defaults (-1 = unlimited, 100 = always); present but non-integer or
// out-of-range values reject the whole entry.
struct InjectParams final : public Serializable {
    int64_t count = -1;
    int32_t probability = 100;

    bool Marshal(Serializable::json &node) const override
    {
        SetValue(node[GET_NAME(count)], count);
        SetValue(node[GET_NAME(probability)], probability);
        return true;
    }

    // Absent, null, non-integer or non-object fields keep the member
    // defaults (GET_NAME ties each key to its member); the final check
    // rejects out-of-range integers so typos surface at load.
    bool Unmarshal(const Serializable::json &node) override
    {
        GetValue(node, GET_NAME(count), count);
        GetValue(node, GET_NAME(probability), probability);
        return count >= -1 && probability >= 0 && probability <= PROBABILITY_MAX_PERCENT;
    }
};

// Per-database entry: the open budget plus operation/method budgets keyed
// by name. Invalid pieces are dropped during unmarshalling; the database
// itself is skipped when its node is not an object.
struct FaultDbEntry final : public Serializable {
    bool openValid = false;
    InjectParams open{};
    std::map<std::string, InjectParams> operations{};
    std::map<std::string, InjectParams> methods{};

    bool Marshal(Serializable::json &node) const override
    {
        return true;
    }

    bool Unmarshal(const Serializable::json &node) override
    {
        openValid = GetValue(node, GET_NAME(open), open);
        GetValue(node, GET_NAME(operations), operations);
        GetValue(node, GET_NAME(methods), methods);
        return true;
    }
};

// Whole config file: databases keyed by name; unknown top-level fields
// are tolerated (forward compatibility).
struct FaultConfig final : public Serializable {
    std::map<std::string, FaultDbEntry> databases{};

    bool Marshal(Serializable::json &node) const override
    {
        return true;
    }

    bool Unmarshal(const Serializable::json &node) override
    {
        GetValue(node, GET_NAME(databases), databases);
        return true;
    }
};

namespace {
constexpr const char *FAULT_CONFIG_NAME = "rdb_fault_inject_config.json";
// Rate limit for distinguishable hit logs: one line per HIT_LOG_INTERVAL
// hits (the first hit always logs).
constexpr int64_t HIT_LOG_INTERVAL = 100;

// In-memory database URIs look like "file:name?mode=memory&cache=shared"
// (generated by SqliteGlobalConfig::GetSharedMemoryDbPath) and carry no
// directory semantics: strip the prefix and query once at construction so
// the bound path is a plain name whose config file resolves CWD-relative.
std::string NormalizeDbPath(const std::string &dbPath)
{
    if (dbPath.rfind("file:", 0) != 0) {
        return dbPath;
    }
    auto path = dbPath.substr(FILE_URI_PREFIX_LEN);
    auto query = path.find('?');
    return query == std::string::npos ? path : path.substr(0, query);
}

std::atomic<int64_t> g_hitLogSeq = { 0 };

void LogHit(const std::string &dbPath, const std::string &what)
{
    int64_t seq = g_hitLogSeq.fetch_add(1, std::memory_order_relaxed);
    if (seq % HIT_LOG_INTERVAL != 0) {
        return;
    }
    LOG_WARN("fault inject hit db[%{public}s] what[%{public}s] seq[%{public}lld]",
        SqliteUtils::Anonymous(dbPath).c_str(), what.c_str(), static_cast<long long>(seq));
}

int OpKeyToEnum(const std::string &key)
{
    if (key == "insert") {
        return static_cast<int>(RdbFaultOp::INSERT);
    }
    if (key == "update") {
        return static_cast<int>(RdbFaultOp::UPDATE);
    }
    if (key == "delete") {
        return static_cast<int>(RdbFaultOp::DELETE);
    }
    if (key == "query") {
        return static_cast<int>(RdbFaultOp::QUERY);
    }
    if (key == "executeSql") {
        return static_cast<int>(RdbFaultOp::EXECUTE_SQL);
    }
    if (key == "transaction") {
        return static_cast<int>(RdbFaultOp::TRANSACTION);
    }
    if (key == "resultSetRead") {
        return static_cast<int>(RdbFaultOp::RESULT_SET_READ);
    }
    return -1;
}

// Cleanup/commit methods: after injection, convergence of transactions and
// result sets relies on caller rollback or destruction.
void WarnCleanupLike(const std::string &name)
{
    static const char *cleanupMethods[] = { "Commit", "Rollback", "Close", "Release" };
    for (auto *cleanupName : cleanupMethods) {
        if (name == cleanupName) {
            LOG_WARN("cleanup-like method [%{public}s] injected; convergence depends on "
                     "caller rollback/destruction",
                name.c_str());
            return;
        }
    }
}

// Reads and unmarshals the config file; false means "treat as not
// configured" (missing file or invalid content).
bool ReadConfigFile(const std::string &path, FaultConfig &config)
{
    std::ifstream fin(path, std::ios::in | std::ios::ate);
    if (!fin.is_open()) {
        return false; // no config file: empty snapshot
    }
    // Hard cap on the config file size: the file is root-controlled debug
    // input, but a runaway test artifact should not stall the open path.
    constexpr std::streamsize MAX_CONFIG_SIZE = 1024 * 1024; // 1 MB
    if (fin.tellg() > MAX_CONFIG_SIZE) {
        LOG_WARN("rdb_fault_inject_config.json too large, treated as no config");
        return false;
    }
    fin.seekg(0, std::ios::beg);
    std::string line;
    std::string content;
    while (std::getline(fin, line)) {
        content += line;
    }
    fin.close();
    if (!config.Unmarshall(content)) {
        LOG_WARN("invalid rdb_fault_inject_config.json, treated as no config");
        return false;
    }
    return true;
}
} // namespace

RdbFaultInjector::RdbFaultInjector(const std::string &dbPath) : dbPath_(NormalizeDbPath(dbPath))
{
    entry_ = LoadEntry();
    enabled_ = entry_ != nullptr && !entry_->IsEmpty();
}

void RdbFaultInjector::CreateOnce(std::shared_ptr<RdbFaultInjector> &holder, const std::string &dbPath)
{
    // Creation reads the config file, so it stays serialized (it runs from
    // the store's Init, outside the store manager's critical section) and
    // idempotent per holder: concurrent opens of one store share the single
    // injector behind the member instead of racing two instances into it.
    static std::mutex createMutex;
    std::lock_guard<std::mutex> lock(createMutex);
    if (holder == nullptr) {
        holder = std::make_shared<RdbFaultInjector>(dbPath);
    }
}

bool RdbFaultInjector::Hit(const std::string &methodName, RdbFaultOp op)
{
    return CheckMethod(methodName) || Check(op);
}

bool RdbFaultInjector::TryConsume(InjectConfig &cfg)
{
    std::lock_guard<std::mutex> lock(cfg.mutex);
    if (cfg.count == 0) {
        return false; // explicit 0 = never inject
    }
    if (cfg.count > 0 && cfg.remaining.load() <= 0) {
        return false; // budget exhausted
    }
    if (cfg.probability <= 0) {
        return false;
    }
    std::uniform_int_distribution<int> dist(0, PROBABILITY_MAX_PERCENT - 1);
    if (dist(cfg.rng) >= cfg.probability) {
        return false; // probability missed: no budget consumed
    }
    if (cfg.count > 0) {
        cfg.remaining.fetch_sub(1);
    }
    return true;
}

std::shared_ptr<RdbFaultInjector::PathEntry> RdbFaultInjector::LoadEntry() const
{
    auto entry = std::make_shared<PathEntry>();
    FaultConfig config;
    if (!ReadConfigFile(StringUtils::ExtractFilePath(dbPath_) + FAULT_CONFIG_NAME, config)) {
        return entry; // no config or invalid content: empty snapshot
    }
    auto dbIt = config.databases.find(StringUtils::ExtractFileName(dbPath_));
    if (dbIt == config.databases.end()) {
        return entry; // database not listed: unaffected
    }
    if (dbIt->second.openValid) {
        ApplyOpen(dbIt->second.open.count, dbIt->second.open.probability, *entry);
    }
    for (const auto &item : dbIt->second.operations) {
        ApplyOperation(item.first, item.second.count, item.second.probability, *entry);
    }
    for (const auto &item : dbIt->second.methods) {
        ApplyMethod(item.first, item.second.count, item.second.probability, *entry);
    }
    return entry;
}

void RdbFaultInjector::ApplyOpen(int64_t count, int32_t probability, PathEntry &entry) const
{
    auto cfg = std::make_shared<InjectConfig>();
    cfg->count = count;
    cfg->probability = probability;
    cfg->remaining.store(count);
    entry.openConfig = cfg;
}

void RdbFaultInjector::ApplyOperation(
    const std::string &key, int64_t count, int32_t probability, PathEntry &entry) const
{
    int op = OpKeyToEnum(key);
    if (op < 0) {
        LOG_WARN("unknown operation key [%{public}s], ignored", key.c_str());
        return;
    }
    auto cfg = std::make_shared<InjectConfig>();
    cfg->count = count;
    cfg->probability = probability;
    cfg->remaining.store(count);
    entry.opConfigs[op] = cfg;
}

void RdbFaultInjector::ApplyMethod(const std::string &name, int64_t count, int32_t probability, PathEntry &entry) const
{
    WarnCleanupLike(name);
    auto cfg = std::make_shared<InjectConfig>();
    cfg->count = count;
    cfg->probability = probability;
    cfg->remaining.store(count);
    entry.methodConfigs[name] = cfg;
}

bool RdbFaultInjector::Check(RdbFaultOp op)
{
    if (!enabled_ || entry_ == nullptr) {
        return false; // hot-path fast gate: one read when unconfigured
    }
    auto cfgIt = entry_->opConfigs.find(static_cast<int>(op));
    if (cfgIt == entry_->opConfigs.end() || cfgIt->second == nullptr) {
        return false;
    }
    if (TryConsume(*cfgIt->second)) {
        LogHit(dbPath_, "op:" + std::to_string(static_cast<int>(op)));
        return true;
    }
    return false;
}

bool RdbFaultInjector::CheckMethod(const std::string &methodName)
{
    if (!enabled_ || entry_ == nullptr) {
        return false;
    }
    auto cfgIt = entry_->methodConfigs.find(methodName);
    if (cfgIt == entry_->methodConfigs.end() || cfgIt->second == nullptr) {
        return false;
    }
    if (TryConsume(*cfgIt->second)) {
        LogHit(dbPath_, "method:" + methodName);
        return true;
    }
    return false;
}

bool RdbFaultInjector::HasEntry() const
{
    return enabled_ && entry_ != nullptr && !entry_->IsEmpty();
}

bool RdbFaultInjector::ConsumeOpen()
{
    if (!enabled_ || entry_ == nullptr || entry_->openConfig == nullptr) {
        return false;
    }
    if (TryConsume(*entry_->openConfig)) {
        LogHit(dbPath_, "open");
        return true;
    }
    return false;
}

